"""Compare CRT predictions with direct finite sieving for selected offsets."""
import argparse
from fractions import Fraction
import json
from pathlib import Path
from src.sieve import (count_interval, direct_survivors, local_bad_count,
                       survivor_classes, survivor_density)

ROOT = Path(__file__).resolve().parents[1]
CASES = ((3,), (-3,), (3, -3), (5,), (-5,), (5, -5), (5, 11))


def run(primes=(2, 3, 5, 7), start=500, stop=1000):
    primes = tuple(primes)
    rows = []
    for offsets in CASES:
        period, classes = survivor_classes(offsets, primes)
        density = survivor_density(offsets, primes)
        count = count_interval(classes, period, start, stop)
        direct = direct_survivors(offsets, primes, start, stop)
        if Fraction(len(classes), period) != density or count != len(direct):
            raise ArithmeticError("CRT counts differ from independent enumeration")
        complete = direct_survivors(offsets, primes, -1, period - 1)
        if complete != classes:
            raise ArithmeticError("full-period density check failed")
        expected = (stop - start) * density
        rows.append({"offsets": list(offsets), "period": period,
                     "bad_counts": {str(p): local_bad_count(offsets, p) for p in primes},
                     "full_period_survivors": len(classes), "density": str(density),
                     "interval_survivors": count, "interval_main_term": str(expected),
                     "interval_error": str(Fraction(count) - expected)})
    return {"scope": "Exact local survival, not primality or prime-witness occupancy",
            "primes": list(primes), "start_exclusive": start,
            "stop_inclusive": stop, "results": rows}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--primes", type=int, nargs="*", default=[2, 3, 5, 7])
    parser.add_argument("--start", type=int, default=500)
    parser.add_argument("--stop", type=int, default=1000)
    parser.add_argument("--output", type=Path, default=ROOT / "results")
    args = parser.parse_args(argv)
    try:
        summary = run(tuple(args.primes), args.start, args.stop)
    except ValueError as error:
        parser.error(str(error))
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "local_sieve.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    lines = ["# Exact finite local sieve", "", "Generated by `python -m experiments.local_sieve`.", "",
             f"Prime set: {args.primes}; interval: {args.start} < m <= {args.stop}.", "",
             "| Offsets | Period | Full-period survivors | Density | Interval survivors |",
             "|---|---:|---:|---:|---:|---:|"]
    for row in summary["results"]:
        lines.append(f"| {row['offsets']} | {row['period']} | {row['full_period_survivors']} | {row['density']} | {row['interval_survivors']} |")
    lines.extend(["", "All CRT predictions were compared with direct enumeration.",
                  "A survivor avoids the selected primes; its value can be composite.", ""])
    (args.output / "local_sieve.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Verified {len(CASES)} local-sieve cases; wrote results to {args.output.resolve()}")


if __name__ == "__main__":
    main()
